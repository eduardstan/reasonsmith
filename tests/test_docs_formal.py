"""Tests holding `docs/formal.md` to the code and claim-to-test map.

The bibliography registry is in `docs/theory/bibliography.md`.

What this module is for:
  `docs/formal.md` states the mathematics of this tool once, in one notation. Three things have to
  be true of it, and none of them survives being asked for politely:

  1. Every `test_*` it names resolves to a test that exists — the discipline
     `tests/test_docs_semantics.py` already applies to `docs/semantics.md`.
  2. Every definition the code also defines is **generated from the code** and compared, so the
     document cannot be edited into disagreement with `Strength`, `BASIS_RUNGS`,
     `rulelang.FRAGMENTS` or `manyvalued.ALGEBRAS`. Three documents each held to the code cannot
     drift apart from each other, which is what makes a fourth document safe to add.
  3. The bibliography in `docs/theory/bibliography.md` is a **registry**: every citation key used
     anywhere in the scanned corpus
     resolves to an entry, every entry is cited by at least one claim, and a source named without a
     key fails the build. This is the new part. Before it, the densest concentration of references
     in the tree was inside `src/reasonsmith/verdict.py`, where nobody looking for a bibliography
     would find them, and nothing stopped the next one landing there too.

What a reader must not break:
  - The generated comparisons must stay generated. Writing the expected chain, table or name list
    as a literal here would move the drift one file over rather than removing it.
  - `SCANNED_EXCLUSIONS` is the corpus boundary and every member is excluded for a stated reason
    (`docs/formal.md`, *The registry*). Widening the corpus is a one-line change; narrowing it
    silently is what the list exists to prevent.
  - Check 3 is a heuristic over a venue-marker list and the other two are not. Deleting a marker
    weakens it invisibly, which is why `VENUE_MARKERS` is asserted non-empty and the document says
    in as many words what the check does not catch.
"""

from __future__ import annotations

import ast
import dataclasses
import re
from pathlib import Path

from reasonsmith.manyvalued import ALGEBRAS
from reasonsmith.rulelang import FRAGMENTS
from reasonsmith.spec import Requirement
from reasonsmith.verdict import BASIS_RUNGS, Strength

REPO_ROOT = Path(__file__).resolve().parent.parent
TESTS_DIR = REPO_ROOT / "tests"
DOCS_DIR = REPO_ROOT / "docs"
FORMAL = DOCS_DIR / "formal.md"
MODELS = DOCS_DIR / "theory" / "01-models.md"
SYNTAX = DOCS_DIR / "theory" / "02-syntax.md"
SEMANTICS = DOCS_DIR / "theory" / "03-semantics.md"
PROCEDURES = DOCS_DIR / "theory" / "05-decision-procedures.md"
BIBLIOGRAPHY = DOCS_DIR / "theory" / "bibliography.md"
ENGINES_DIR = REPO_ROOT / "src" / "reasonsmith" / "engines"

#: A `test_...` identifier as the document writes them. A name followed by `.py` is a module the
#: document points at, not a claim's enforcing test.
_TEST_NAME = re.compile(r"\btest_[a-z0-9_]+\b(?!\.py)")

#: A citation, in the one form the document's key convention admits: a backticked, pandoc-style
#: `[@key]`. The at-sign is what keeps this off `[grading] algebra` and off a markdown link, and
#: the surrounding backticks are what keep it off `details[PROBE_BUDGET_KEY]`.
_CITATION_KEY = re.compile(r"`\[@([a-z][a-z0-9-]*)\]`")

#: A bibliography entry, which is a list item whose first token is its own key in bold.
_BIBLIOGRAPHY_ENTRY = re.compile(r"^- \*\*`\[@([a-z][a-z0-9-]*)\]`\*\*")

#: Files inside the scanned directories that carry no citable prose. Each is excluded for a reason
#: `docs/formal.md` states; none is excluded because keying it was inconvenient.
SCANNED_EXCLUSIONS = (
    "example-output.md",  # generated byte-for-byte by a builder
    "nesyarena-conformance-report.md",  # generated byte-for-byte by a builder
    "legal-sources.md",  # statutory retrieval record; its sources are laws, tracked by drift.py
)

#: Publication-venue markers. A block of prose carrying one of these and no citation key is a
#: source that landed without being registered. The list is deliberately conservative: every entry
#: is a venue this repository actually cites, because a marker that fires on ordinary prose is a
#: check somebody switches off.
VENUE_MARKERS = (
    "AAAI",
    "NeurIPS",
    "IJCAI",
    "ECAI",
    "CSFW",
    "TABLEAUX",
    "AIxIA",
    "CHARME",
    "ACL 20",
    "SAS 20",
    "JAIR",
    "Kluwer",
    "et al.",
    "LNCS",
    "Information Processing Letters",
    "Journal of Computer Security",
    "Journal of Artificial Intelligence Research",
    "Annals of Mathematics and Artificial Intelligence",
    "Artificial Intelligence and Law",
    "Formal Methods in System Design",
    "Trends in Logic",
    "Software Tools for Technology Transfer",
    "Transactions on Software Engineering and Methodology",
)

#: Cardinal numbers as the document writes them (prose, not numerals).
_NUMBER_WORDS = (
    "zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine",
    "ten", "eleven", "twelve", "thirteen", "fourteen", "fifteen", "sixteen",
    "seventeen", "eighteen", "nineteen", "twenty",
)


def _document() -> str:
    assert FORMAL.is_file(), f"{FORMAL} does not exist"
    return FORMAL.read_text(encoding="utf-8")


def _scanned_files() -> list[Path]:
    """The corpus the registry is enforced over: documentation prose and package sources."""
    files = [p for p in sorted(DOCS_DIR.rglob("*.md")) if p.name not in SCANNED_EXCLUSIONS]
    files += sorted((REPO_ROOT / "src" / "reasonsmith").rglob("*.py"))
    return files


def _bibliography_keys() -> dict[str, str]:
    """Every key the bibliography defines, mapped to the line that defines it."""
    keys: dict[str, str] = {}
    for line in BIBLIOGRAPHY.read_text(encoding="utf-8").splitlines():
        match = _BIBLIOGRAPHY_ENTRY.match(line)
        if match:
            keys[match.group(1)] = line
    return keys


def _defined_test_names() -> set[str]:
    """Every test function name this suite defines, read from the sources rather than collected."""
    names: set[str] = set()
    for path in sorted(TESTS_DIR.glob("test_*.py")):
        tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
        for node in ast.walk(tree):
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name.startswith(
                "test_"
            ):
                names.add(node.name)
    return names


def _section(title: str, path: Path = FORMAL) -> str:
    """The text of one heading in a document, up to the next heading of equal level."""
    document = path.read_text(encoding="utf-8")
    start = document.index(title)
    rest = document[start + len(title) :]
    end = rest.find("\n## ")
    return rest if end < 0 else rest[:end]


