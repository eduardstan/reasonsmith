def test_the_formal_doc_states_the_chain_the_code_defines():
    """§4.1's ordering sentence is generated from `Strength`, not written from memory."""
    chain = " < ".join(s.value for s in sorted(Strength))
    assert chain == "unattainable < observed < recounted < probed < proved"
    assert chain in _document(), (
        "docs/formal.md §4.1 does not state the chain `Strength` defines; it must read: " + chain
    )


def test_the_authoring_docs_state_the_chain_the_code_defines():
    """The authoring documents' parenthetical enumerations of `Strength` members are
    generated from `sorted(Strength)`, so a rung added later cannot leave them behind.

    `recounted` once went missing from the `max_strength` field's parenthetical in
    `docs/authoring-engines.md`, and nothing in this generated-from-code family read the
    authoring documents at all.
    """
    chain = ", ".join(s.value for s in sorted(Strength))
    members = {s.value for s in Strength}
    for doc in (DOCS_DIR / "authoring-engines.md", DOCS_DIR / "authoring-packs.md"):
        for parenthetical in re.findall(r"\(([^()]*)\)", doc.read_text(encoding="utf-8")):
            names = [re.sub(r"[`\s]", "", n) for n in parenthetical.split(",")]
            names = [n for n in names if n]
            if len(names) > 1 and set(names) <= members:
                assert ", ".join(names) == chain, (
                    f"{doc.name} enumerates Strength members ({', '.join(names)}) but "
                    f"the lattice is {chain}"
                )


def test_the_formal_doc_states_the_requirement_field_count_the_code_defines():
    """§1.4's count sentence is generated from `Requirement`, not written from memory.

    The sentence once read twelve against the class's fifteen fields, and a prose number is
    exactly what this family exists to generate.
    """
    count = len(dataclasses.fields(Requirement))
    word = _NUMBER_WORDS[count]
    field_sentence = f"carries exactly {word} fields"
    assert field_sentence in _document() or field_sentence in MODELS.read_text(encoding="utf-8"), (
        "the models chapter or pending migration does not state the field count `Requirement` "
        "defines; "
        f"it must read: carries exactly {word} fields"
    )


def test_the_formal_doc_states_the_basis_rungs_the_code_defines():
    """§4.3's table is generated from `BASIS_RUNGS`, row by row.

    A row widened in the code and not here — or here and not in the code — is what this catches,
    and it is the table three module docstrings used to state in prose apiece.
    """
    document = _document()
    for basis, rungs in BASIS_RUNGS.items():
        row = f"| `{basis.value}` | " + ", ".join(f"`{r.value}`" for r in rungs) + " |"
        assert row in document, (
            f"docs/formal.md §4.3 does not carry the row for {basis.value}: {row}"
        )

    assert document.count("| Basis | Admits |") == 1, "§4.3's table is stated more than once"


def test_the_formal_doc_names_the_fragments_the_classifier_defines():
    """§2.9's classification order names exactly the fragments `rulelang` has, and no others."""
    section = _section("**Definition 2.6 (fragment assignment).**", SYNTAX)
    code = section[section.index("```") : section.index("```", section.index("```") + 3)]
    named = set(re.findall(r'"([a-z]+)"', code))
    assert named == set(FRAGMENTS), (
        "the syntax chapter names fragments the classifier does not have, or omits ones it does: "
        f"document {sorted(named)} vs code {sorted(FRAGMENTS)}"
    )


def test_the_formal_doc_names_the_algebras_the_code_defines():
    """§5.2's table names exactly `manyvalued.ALGEBRAS`, so a fourth member cannot be silent."""
    section = _section("**Definition 3.3 (the shipped algebras).**", SEMANTICS)
    rows = re.findall(r"^\| `([a-z]+)` \|", section, flags=re.MULTILINE)
    assert set(rows) == set(ALGEBRAS), (
        "docs/formal.md §5.2 does not name the algebras the code defines: "
        f"document {sorted(rows)} vs code {sorted(ALGEBRAS)}"
    )


def test_the_formal_doc_states_one_soundness_paragraph_per_engine():
    """§6 names every engine under `engines/`, so a new one cannot ship without a statement."""
    engines = sorted(
        p.stem for p in ENGINES_DIR.glob("*.py") if not p.stem.startswith("_")
    )
    assert engines, "no engine modules found; the directory this reads has moved"

    section = _document() + "\n" + PROCEDURES.read_text(encoding="utf-8")
    missing = [name for name in engines if f"`{name}`" not in section and name not in section]
    assert not missing, (
        "the decision-procedures chapter states no soundness paragraph for engine(s): "
        + ", ".join(missing)
    )


